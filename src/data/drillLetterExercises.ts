export function getDrillExerciseForLetter(letterOrKey: string): DrillLetterExercise {
  const clean = letterOrKey
    .replace('letter_', '')
    .replace(/[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/g, '')
    .trim();
  const letter = clean ? clean[0] : 'م';

  if (DRILL_LETTER_EXERCISES[letter]) {
    return DRILL_LETTER_EXERCISES[letter];
  }

  // Fallback exercise for any unmapped letter
  return {
    letter,
    nameUz: `«${letter}» harfi`,
    categoryUz: 'Maxraj va Tajvid',
    makhrajTipUz: `«${letter}» harfining maxraj a'zolariga to'liq diqqat qiling va sifatini saqlang.`,
    ruleDescriptionUz: `«${letter}» harfi qiroatda to'g'ri maxraj va harakat bilan o'qilishi zarur. Namunani tinglab, mikrofonga talaffuz qiling.`,
    commonMistakeUz: "Harakatning noaniqligi yoki o'xshash tovush bilan almashib qolishi.",
    words: [
      {
        id: `drill_${letter}_001`,
        textUthmani: letter,
        transliteration: letter,
        ayahRef: "Qur'on misoli",
        meaningUz: "Talaffuz mashqi",
        audioUrl: 'https://audio.qurancdn.com/wbw/001_001_001.mp3',
        targetPart: letter,
        rule: 'makhraj_critical',
        expectedPhonemeIPA: letter,
      },
    ],
  };
}

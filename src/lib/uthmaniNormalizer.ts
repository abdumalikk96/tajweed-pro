/**
 * Каноническая нормализация Усманийского расма Мусхафа к современному орфографическому стандарту (Имлаи)
 * и очистка вводных религиозных формул (Исти'аза, Басмала).
 */

export function normalizeUthmaniToImlai(text: string): string {
  if (!text) return '';
  let t = text;

  // 1. Нечитаемые усманийские знаки (\u06DF, \u06E0, \u06E5, \u06E6, \u0653)
  t = t.replace(/[\u06DF\u06E0\u06E5\u06E6\u0653]/g, '');

  // 2. Специфические составные обращения, указательные местоимения и слитные формы
  t = t.replace(/يَ?\s*ٰ?\s*ٓ?\s*أَيُّ?\s*هَ\s*ا/g, 'ياايها');
  t = t.replace(/يا\s+أ?يها/g, 'ياايها');
  t = t.replace(/يَ?\s*ٰ?\s*ٓ?\s*أَبَتِ?/g, 'ياابت');
  t = t.replace(/هَ?\s*ٰ?\s*ٓ?\s*ؤُلَ\s*آ?\s*ءِ?/g, 'هاولاء');
  t = t.replace(/ه[ؤو]ل[اآ]ء?/g, 'هاولاء');
  t = t.replace(/أُو۟?\s*لَ\s*ٰ?\s*ٓ?\s*ئِ\s*كَ/g, 'اولئك');
  t = t.replace(/ا[وؤ]ل[اآئ]ك/g, 'اولئك');
  t = t.replace(/هَ?\s*ٰ?\s*ذَ\s*ا/g, 'هذا');
  t = t.replace(/هَ?\s*ٰ?\s*ذِ\s*هِ/g, 'هذه');
  t = t.replace(/ذَ?\s*ٰ?\s*لِ\s*كَ/g, 'ذلك');
  t = t.replace(/لَ?\s*ٰ?\s*كِ\s*نَّ?/g, 'لكن');

  // 3. Вав и йа с алиф-ханджарией (صلوة -> صلاة, زكوة -> زكاة, حيوة -> حياة, الربوا -> الربا)
  t = t.replace(/و[\u064B-\u065F]*\u0670/g, 'ا');
  t = t.replace(/ي[\u064B-\u065F]*\u0670/g, 'ا');
  t = t.replace(/ى[\u064B-\u065F]*\u0670/g, 'ا');

  // 4. Одиночная алиф-ханджария (مَٰلِكِ -> مالك, ٱلْعَٰلَمِينَ -> العالمين)
  t = t.replace(/\u0670/g, 'ا');

  // 5. Удаление огласовок (харакатов) и коранических знаков
  t = t.replace(/[\u0610-\u061A\u064B-\u065F\u06D6-\u06ED]/g, '');

  // 6. Унификация всех видов хамзы/алифа и та марбута
  t = t.replace(/[إأآٱءؤئى]/g, 'ا');
  t = t.replace(/ة/g, 'ه');

  // 7. Сжатие сдвоенных алифов и очистка лишних символов
  t = t.replace(/ا+/g, 'ا');
  t = t.replace(/[^\u0621-\u064A\s]/g, '');
  return t.replace(/\s+/g, ' ').trim();
}

export function stripIstiadhaAndBasmala(rec: string, exp: string): string {
  if (!rec) return '';
  let r = rec.trim();
  const e = (exp || '').trim();
  const normE = e.replace(/[^\u0621-\u064A\s]/g, '');
  if (normE.includes('بسم الله')) {
    return r;
  }

  const patterns = [
    /^\s*أعوذ\s+بالله\s+من\s+الشيطان\s+الرجيم\s*/i,
    /^\s*اعوذ\s+بالله\s+من\s+الشيطان\s+الرجيم\s*/i,
    /^\s*أعوذ\s+بالله\s*/i,
    /^\s*اعوذ\s+بالله\s*/i,
    /^\s*بسم\s+الله\s+الرحمن\s+الرحيم\s*/i,
    /^\s*بسم\s+الله\s*/i,
  ];

  for (const p of patterns) {
    r = r.replace(p, '').trim();
  }
  return r;
}
